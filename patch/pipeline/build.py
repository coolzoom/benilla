#!/usr/bin/env python3
"""Build a custom map scene into one 1.12.1 client MPQ and the vmangos world-DB patch.

    patch/.venv/bin/python patch/pipeline/build.py --scene tiangong

Outputs (relative to patch/):
    client/patch-5.MPQ          world assets (WDT/ADT/WMO/BLP, loading screen) and the DBFilesClient overrides
                                -> <client>/Data/   (1.12 has no locale folder; patch-?.MPQ outranks patch.MPQ)
    db/<scene>_world.sql        map_template / area_template / game_tele rows for vmangos (+ _rollback.sql)
    build/<scene>/files/        loose copies of every generated file (for tests / server extraction)
    build/<scene>/manifest.json config, spawn, walk path and floor probes for the tests

vmangos reads no Map.dbc or AreaTable.dbc: the map and zone come from the world DB, the terrain and collision from
the map/vmap files pipeline/extract_server.py makes out of the same MPQ contents.
"""
import argparse
import importlib.util
import json
import os
import shutil
import sys

PATCH = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(PATCH, "tools"))

import adt  # noqa: E402
import blp  # noqa: E402
import mpq  # noqa: E402
import numpy as np  # noqa: E402
import wowfmt  # noqa: E402
from dbc import DBC, f2u, i2u  # noqa: E402
from wmo import POLY_DETAIL  # noqa: E402
from PIL import Image  # noqa: E402

DBC_NAMES = ["Map", "AreaTable", "Light", "LightParams", "LightIntBand", "LightFloatBand", "LoadingScreens"]
FIELDS = {"Map": 42, "AreaTable": 25, "Light": 12, "LightParams": 9, "LightIntBand": 34, "LightFloatBand": 34,
          "LoadingScreens": 3}
OUR_MPQ = "patch-5.MPQ"
LIGHT_SLOT_DEATH_PARAMS = 4   # every stock Light row's death slot


def load_scene(name):
    path = os.path.join(PATCH, "scenes", name, "scene.py")
    spec = importlib.util.spec_from_file_location(f"scene_{name}", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def base_dbcs(cache_dir):
    """Stock client DBCs (read once from the MPQ chain without our own patch, then cached)."""
    os.makedirs(cache_dir, exist_ok=True)
    missing = [n for n in DBC_NAMES if not os.path.exists(os.path.join(cache_dir, n + ".dbc"))]
    if missing:
        chain = mpq.Chain(mpq.client_chain(skip=(OUR_MPQ,)))
        for n in missing:
            data = chain.read(f"DBFilesClient\\{n}.dbc")
            assert data, n
            with open(os.path.join(cache_dir, n + ".dbc"), "wb") as fh:
                fh.write(data)
        chain.close()
    dbcs = {n: DBC.load(os.path.join(cache_dir, n + ".dbc")) for n in DBC_NAMES}
    for n, d in dbcs.items():
        assert d.fields == FIELDS[n], (n, d.fields)
    return dbcs


def _put(d, name, rec):
    assert len(rec) == FIELDS[name], (name, len(rec))
    d.put(rec)


def patch_dbcs(d, cfg, light):
    mid, aid, ls_id = cfg["map_id"], cfg["area_id"], cfg["loading_screen_id"]
    m = d["Map"]
    rec = [mid, m.add_string(cfg["directory"]), 0, 0] + m.loc(cfg["name"])
    rec += [0, 0, 0, i2u(-1), 0, 0, aid]
    rec += m.loc(cfg["description"]) + m.loc(cfg["description"])
    rec += [ls_id, 0, 1, f2u(1.0)]
    _put(m, "Map", rec)

    a = d["AreaTable"]
    rec = [aid, mid, 0, cfg["area_bit"], 0x40, 0, 0, 0, 0, 0, cfg["area_level"]] + a.loc(cfg["name"])
    rec += [0, 0, 0, 0, 0]
    _put(a, "AreaTable", rec)

    ls = d["LoadingScreens"]
    _put(ls, "LoadingScreens", [ls_id, ls.add_string("TianGong"), ls.add_string(cfg["loading_screen"])])

    lp = cfg["light_params_id"]
    _put(d["Light"], "Light", [cfg["light_id"], mid, f2u(0), f2u(0), f2u(0), f2u(0), f2u(0),
                               lp, lp, lp, lp, LIGHT_SLOT_DEATH_PARAMS])
    _put(d["LightParams"], "LightParams",
         [lp, 0, 0, 0, f2u(0.2), f2u(0.5), f2u(1.0), f2u(0.75), f2u(1.0)])
    for band in range(18):
        _put(d["LightIntBand"], "LightIntBand",
             [(lp - 1) * 18 + band + 1, 1, 0] + [0] * 15 + [light["int"].get(band, 0)] + [0] * 15)
    for band in range(6):
        _put(d["LightFloatBand"], "LightFloatBand",
             [(lp - 1) * 6 + band + 1, 1, 0] + [0] * 15 + [f2u(light["float"].get(band, 0.0))] + [0] * 15)


def _q(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "''") + "'"


def write_sql(scene_name, cfg, spawn):
    """Idempotent vmangos world-DB patch: the map, its zone and the GM teleport entry."""
    mid, aid, tid = cfg["map_id"], cfg["area_id"], cfg["tele_id"]
    sx, sy, sz, so = spawn
    lines = [
        f"-- {cfg['name']} ({scene_name}): generated by patch/pipeline/build.py, safe to re-run",
        "SET NAMES utf8mb4;",
        f"DELETE FROM `map_template` WHERE `entry` = {mid};",
        "INSERT INTO `map_template` (`entry`, `patch`, `parent`, `map_type`, `linked_zone`, `player_limit`, "
        "`reset_delay`, `ghost_entrance_map`, `ghost_entrance_x`, `ghost_entrance_y`, `map_name`, `script_name`) "
        f"VALUES ({mid}, 0, 0, 0, 0, 0, 0, -1, 0, 0, {_q(cfg['name'])}, '');",
        f"DELETE FROM `area_template` WHERE `entry` = {aid};",
        "INSERT INTO `area_template` (`entry`, `map_id`, `zone_id`, `explore_flag`, `flags`, `area_level`, `name`, "
        f"`team`, `liquid_type`) VALUES ({aid}, {mid}, 0, {cfg['area_bit']}, 64, {cfg['area_level']}, "
        f"{_q(cfg['name'])}, 0, 0);",
        f"DELETE FROM `game_tele` WHERE `id` = {tid} OR `name` = {_q(cfg['tele_name'])};",
        "INSERT INTO `game_tele` (`id`, `position_x`, `position_y`, `position_z`, `orientation`, `map`, `name`) "
        f"VALUES ({tid}, {sx:.3f}, {sy:.3f}, {sz:.3f}, {so:.4f}, {mid}, {_q(cfg['tele_name'])});",
        "",
    ]
    rollback = [
        f"-- rollback for {scene_name}",
        f"DELETE FROM `map_template` WHERE `entry` = {mid};",
        f"DELETE FROM `area_template` WHERE `entry` = {aid};",
        f"DELETE FROM `game_tele` WHERE `id` = {tid};",
        "",
    ]
    db = os.path.join(PATCH, "db")
    os.makedirs(db, exist_ok=True)
    with open(os.path.join(db, f"{scene_name}_world.sql"), "w") as fh:
        fh.write("\n".join(lines))
    with open(os.path.join(db, f"{scene_name}_world_rollback.sql"), "w") as fh:
        fh.write("\n".join(rollback))


def walk_probes(scene, cfg, tris, n_probes=8):
    """Expected floor heights (world coords) along the scene's WALK_PATH, for server-side collision tests."""
    x, y, z, _ = cfg["spawn_local"]
    path = [list(p) for p in getattr(scene, "WALK_PATH", [(x, y)])]
    if len(path) < 2:
        path.append(list(path[0]))
    steps = wowfmt.walk(tris, path, wowfmt.ray_down(tris, x, y, z + 2))
    ox, oy = cfg["origin"]
    pick = sorted({round(i * (len(steps) - 1) / (n_probes - 1)) for i in range(n_probes)})
    return path, [[steps[i][0] + ox, steps[i][1] + oy, steps[i][2]] for i in pick]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--scene", default="tiangong")
    args = ap.parse_args()

    scene = load_scene(args.scene)
    cfg = scene.CONFIG
    out_dir = os.path.join(PATCH, "build", args.scene)
    loose = os.path.join(out_dir, "files")
    if os.path.isdir(loose):
        shutil.rmtree(loose)
    os.makedirs(loose)
    world = {}

    print("textures...")
    for path, (img, has_alpha) in scene.textures().items():
        world[path] = blp.encode(img, alpha=has_alpha)

    print("loading screen...")
    src = os.path.join(PATCH, "scenes", args.scene, "loading", "loading_4x3.png")
    img = Image.open(src).convert("RGB").resize((512, 512), Image.Resampling.LANCZOS)
    world[cfg["loading_screen"]] = blp.encode(img, alpha=False)

    print("wmos...")
    wmo_names, modf, manifest, solid = [], [], [], []
    for i, (path, files, (lo, hi), pos, mesh) in enumerate(scene.wmos()):
        faces = np.array([f[:3] for f in mesh.faces if not f[4] & POLY_DETAIL], dtype=np.int64).reshape(-1, 3)
        solid.append(np.asarray(mesh.pos, dtype=np.float32)[faces])
        for suffix, data in files.items():
            world[path[:-4] + suffix + ".wmo"] = data
        wmo_names.append(path)
        modf.append(adt.modf_entry(i, 800000 + i, pos, lo, hi))
        manifest.append({"path": path, "groups": len(files) - 1, "faces": len(mesh.faces),
                         "verts": len(mesh.pos)})
        print(f"  {path}: {len(files) - 1} groups, {len(mesh.faces)} tris")

    print("terrain...")
    d = cfg["directory"]
    world[f"World\\Maps\\{d}\\{d}.wdt"] = adt.build_wdt(cfg["tiles"])
    textures, alpha_fns = scene.terrain_layers()
    for fx, fy in cfg["tiles"]:
        world[f"World\\Maps\\{d}\\{d}_{fx}_{fy}.adt"] = adt.build_adt(fx, fy, scene.terrain_height, textures,
                                                                      alpha_fns, cfg["area_id"], wmo_names, modf)

    print("dbc...")
    dbcs = base_dbcs(os.path.join(PATCH, "build", "base_dbc"))
    patch_dbcs(dbcs, cfg, scene.LIGHT)
    dbc_files = {f"DBFilesClient\\{n}.dbc": dbcs[n].serialize() for n in DBC_NAMES}

    files = {**world, **dbc_files}
    for name, data in files.items():
        p = os.path.join(loose, *name.split("\\"))
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "wb") as fh:
            fh.write(data)

    client = os.path.join(PATCH, "client")
    os.makedirs(client, exist_ok=True)
    mpq.build(os.path.join(client, OUR_MPQ), files)
    sx, sy, sz, so = scene.spawn_world()
    write_sql(args.scene, cfg, (sx, sy, sz, so))
    walk_path, probes = walk_probes(scene, cfg, np.concatenate(solid))
    info = {"scene": args.scene, "config": cfg, "spawn": [sx, sy, sz, so], "wmos": manifest,
            "walk_path": walk_path, "probes": probes, "world_files": sorted(world), "dbc_files": sorted(dbc_files)}
    with open(os.path.join(out_dir, "manifest.json"), "w") as fh:
        json.dump(info, fh, ensure_ascii=False, indent=1)
    print(f"done: {len(world)} world files + {len(dbc_files)} dbc, spawn {sx:.2f} {sy:.2f} {sz:.2f}")


if __name__ == "__main__":
    main()
